import argparse
import json
import subprocess
import sys
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent

def run_step(script_name, description, extra_args=None):
    print(f"\n==========================================")
    print(f"  [RUN] {description} ({script_name})")
    print(f"==========================================")
    cmd = [sys.executable, str(BASE_DIR / script_name)]
    if extra_args:
        cmd.extend(extra_args)
    res = subprocess.run(cmd)
    if res.returncode != 0:
        print(f"[ERROR] Step {script_name} failed with code {res.returncode}", file=sys.stderr)
        sys.exit(res.returncode)

def run_check():
    print("\n=== Puti-AI 3D Clay Environment & Contract Health Check ===")
    has_error = False

    # 1. 檢查 Python 鎖定版本依賴
    python_packages = [
        ("playwright", "playwright"),
        ("edge_tts", "edge-tts"),
        ("yaml", "PyYAML"),
        ("soundfile", "soundfile"),
        ("numpy", "numpy")
    ]
    for mod_name, pkg_name in python_packages:
        try:
            mod = __import__(mod_name)
            ver = getattr(mod, "__version__", "installed")
            print(f"  [OK] Python Package : {pkg_name} ({ver})")
        except ImportError:
            print(f"  [MISSING] Python Pkg: {pkg_name} (run: pip install -r requirements.txt)")
            has_error = True

    # 2. 檢查字型資產
    font_huninn = BASE_DIR / "fonts" / "huninn.ttf"
    font_noto = BASE_DIR / "fonts" / "NotoSansTC-VF.ttf"
    for f in [font_huninn, font_noto]:
        if f.exists():
            print(f"  [OK] Font Asset     : {f.name}")
        else:
            print(f"  [MISSING] Font Asset: {f}")
            has_error = True

    # 3. 檢查核心契約與資料檔
    core_files = [
        BASE_DIR / "scene.html",
        BASE_DIR / "style.yaml",
        BASE_DIR / "style.js",
        BASE_DIR / "cues.json",
        BASE_DIR / "sfx.json"
    ]
    for item in core_files:
        if item.exists():
            print(f"  [OK] Core Contract  : {item.name}")
        else:
            print(f"  [MISSING] Core File : {item.name}")
            has_error = True

    # 4. 驗證 style.yaml 與 style.js 是否同步（防止靜默走鐘）
    try:
        import yaml
        with open(BASE_DIR / "style.yaml", "r", encoding="utf-8") as yf:
            yaml_data = yaml.safe_load(yf)
        expected_js = f"// Auto-generated by compile_style.py from style.yaml\nwindow.CLAY_STYLE = {json.dumps(yaml_data, ensure_ascii=False, indent=2)};\n"
        with open(BASE_DIR / "style.js", "r", encoding="utf-8") as jf:
            actual_js = jf.read()
        if expected_js.strip() == actual_js.strip():
            print("  [OK] Style Sync     : style.yaml <==> style.js 內容 100% 同步")
        else:
            print("  [OUT OF SYNC] Style Sync : style.js 與 style.yaml 不一致！請執行 python build.py --style")
            has_error = True
    except Exception as e:
        print(f"  [ERROR] Style Sync check failed: {e}")
        has_error = True

    # 5. 驗證 sfx.json 資料合法性
    try:
        with open(BASE_DIR / "cues.json", "r", encoding="utf-8") as cf:
            total_dur = json.load(cf).get("total", 62.32)
        with open(BASE_DIR / "sfx.json", "r", encoding="utf-8") as sf:
            sfx_items = json.load(sf)
        sfx_err = False
        for s in sfx_items:
            s_file = BASE_DIR / "audio" / s["file"]
            if not s_file.exists():
                print(f"  [SFX MISSING] 音效檔不存在: {s['file']}")
                sfx_err = True
            if not (0.0 <= s["time"] <= total_dur):
                print(f"  [SFX RANGE] 時間點 {s['time']}s 超出影片長度 {total_dur}s")
                sfx_err = True
        if not sfx_err:
            print(f"  [OK] SFX Integrity  : {len(sfx_items)} 項音效時間軸與實體檔合法性檢驗通過")
        else:
            has_error = True
    except Exception as e:
        print(f"  [ERROR] SFX Integrity check failed: {e}")
        has_error = True

    # 6. 檢查系統工具 (FFmpeg, FFprobe)
    for tool in ["ffmpeg", "ffprobe"]:
        try:
            ver = subprocess.check_output([tool, "-version"], stderr=subprocess.DEVNULL).decode('utf-8').split('\n')[0]
            print(f"  [OK] System Tool    : {tool} ({ver.split()[2]})")
        except Exception:
            print(f"  [MISSING] CLI Tool  : {tool} not found in PATH!")
            has_error = True

    if not has_error:
        print("\nAll checks passed! Project is fully verified, synchronized, and ready to render.")
    else:
        print("\nHealth check failed. Please resolve above issues.", file=sys.stderr)
        sys.exit(1)

def main():
    parser = argparse.ArgumentParser(description="Puti-AI 3D Clay Explainer Video Master Build Pipeline")
    parser.add_argument("--check", action="store_true", help="Run comprehensive health, sync, and integrity check")
    parser.add_argument("--style", action="store_true", help="Compile style.yaml to style.js")
    parser.add_argument("--audio", action="store_true", help="Build procedural SFX, BGM, and master mix (normalize=0)")
    parser.add_argument("--subtitles", action="store_true", help="Generate SRT and VTT subtitles from cues.json")
    parser.add_argument("--render", action="store_true", help="Run Playwright offline 1080p render")
    parser.add_argument("--aspect", choices=["16:9", "9:16"], default="16:9", help="Video aspect ratio (default: 16:9)")
    parser.add_argument("--fps", type=int, default=30, help="Framerate (default: 30)")
    parser.add_argument("--all", action="store_true", help="Execute full build: style -> audio -> subtitles -> render")

    args = parser.parse_args()

    if not (args.check or args.style or args.audio or args.subtitles or args.render or args.all):
        parser.print_help()
        return

    if args.check:
        run_check()

    if args.style or args.all:
        run_step("compile_style.py", "Compiling style.yaml -> style.js")

    if args.audio or args.all:
        run_step("synth_sfx.py", "Synthesizing Procedural Audio & BGM")
        run_step("mix_audio.py", "Mixing Audio Master (normalize=0, cues.json + sfx.json)")

    if args.subtitles or args.all:
        run_step("export_subtitles.py", "Exporting Subtitles (SRT / VTT)")

    if args.render or args.all:
        render_args = ["--aspect", args.aspect, "--fps", str(args.fps)]
        run_step("render_video.py", f"Rendering 1080p 3D Clay Stop-Motion ({args.aspect})", extra_args=render_args)

if __name__ == "__main__":
    main()
