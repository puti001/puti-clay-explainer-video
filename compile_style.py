import json
from pathlib import Path
import yaml

BASE_DIR = Path(__file__).resolve().parent
STYLE_YAML = BASE_DIR / "style.yaml"
STYLE_JS = BASE_DIR / "style.js"

def compile_style():
    if not STYLE_YAML.exists():
        print(f"Error: {STYLE_YAML} not found.")
        return False
        
    with open(STYLE_YAML, "r", encoding="utf-8") as f:
        data = yaml.safe_load(f)

    js_content = f"// Auto-generated by compile_style.py from style.yaml\nwindow.CLAY_STYLE = {json.dumps(data, ensure_ascii=False, indent=2)};\n"
    STYLE_JS.write_text(js_content, encoding="utf-8")
    print(f"Compiled {STYLE_YAML.name} -> {STYLE_JS.name}")
    return True

if __name__ == "__main__":
    compile_style()
